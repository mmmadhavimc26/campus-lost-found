CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id BIGINT NOT NULL REFERENCES app_users(id),
 kind VARCHAR(10) NOT NULL,
 title VARCHAR(100) NOT NULL,
 category VARCHAR(30) NOT NULL,
 location VARCHAR(40) NOT NULL,
 event_date DATE NOT NULL,
 description VARCHAR(700) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
);
CREATE TABLE claims (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id BIGINT NOT NULL REFERENCES reports(id),
 claimant_id BIGINT NOT NULL REFERENCES app_users(id),
 private_details VARCHAR(1500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 CONSTRAINT uq_claim UNIQUE(report_id, claimant_id)
);
CREATE INDEX idx_reports_matching ON reports(category, kind, event_date);
CREATE INDEX idx_claimant ON claims(claimant_id);
